async function run() {
  let client;
  let connected = false;

  for (const connStr of connectionStrings) {
    console.log(`Trying to connect with: ${connStr.replace(/:[^@:]+@/, ':****@')}`);
    try {
      client = new Client({ connectionString: connStr });
      await client.connect();
      console.log("✅ Successfully connected to Supabase PostgreSQL!");
      connected = true;
      break;
    } catch (e) {
      console.log(`❌ Connection failed: ${e.message}`);
    }
  }

  if (!connected) {
    console.error("❌ Could not connect using any of the password options.");
    process.exit(1);
  }

  console.log("\nExecuting schema migration...");
  for (const stmt of sqlStatements) {
    try {
      await client.query(stmt);
      console.log(`✅ Executed statement successfully.`);
    } catch (e) {
      console.error(`❌ Statement failed: ${e.message}`);
      console.error(`Statement: ${stmt}\n`);
    }
  }

  await client.end();
  console.log("\n✨ Schema setup complete!");
}

run();
